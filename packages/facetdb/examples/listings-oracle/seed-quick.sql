-- A quick run's sample data on Oracle Database 19c and later: the same marketplace LISTINGS table
-- as seed.sql with 100 rows (five of them written like a scam), for trying a change in minutes.
-- Run it before `facetdb migrate` (sqlplus <admin>@tcps://<host>:2484/<service> @seed-quick.sql); the
-- trigger sets UPDATED_AT when TITLE or DESCRIPTION changes, which FacetDB polls by. The user who
-- runs it needs create table, create sequence (for the identity column; ORA-01031 without it)
-- and create trigger.
create table listings (
  id number generated by default as identity primary key,
  title varchar2(200 char) not null,
  description varchar2(1000 char),
  created_at timestamp default systimestamp not null,
  updated_at timestamp default systimestamp not null
);

create or replace trigger listings_updated_at
  before update of title, description on listings
  for each row
begin
  :new.updated_at := systimestamp;
end;
/

insert into listings (title, description)
select
  case mod(n, 3)
    when 0 then case mod(trunc(n / 3), 4) when 0 then '2015 Toyota Corolla, 98k km' when 1 then 'Honda CB500 motorbike, serviced' when 2 then 'Ford Transit van, long wheelbase' else 'VW Golf 1.4, one owner' end
    when 1 then case mod(trunc(n / 3), 4) when 0 then 'Two-bedroom flat near the station' when 1 then 'Room in a shared house, bills included' when 2 then 'Family house with garden, 3 beds' else 'Studio to rent, furnished' end
    else case mod(trunc(n / 3), 4) when 0 then 'Trek mountain bike, 29 inch' when 1 then 'Road bike carbon frame, 56 cm' when 2 then 'Kids bike with stabilisers' else 'Shimano groupset and wheels' end
  end
  || ' #' || n,
  case
    when mod(n, 20) = 0 then
      'URGENT. Owner abroad, item is at a shipping agent. Pay the deposit by gift card or crypto today and we deliver tomorrow. No viewing possible, contact only on WhatsApp +00 000 000.'
    when mod(n, 3) = 0 then
      'Full service history, MOT until next year, two keys. Viewing welcome at my home address, cash or bank transfer on collection.'
    when mod(n, 3) = 1 then
      'Close to shops and schools, recently redecorated, deposit and first month on signing. Viewings by appointment through the agency.'
    else
      'Good condition, a few scratches, recently serviced. Collection only, happy to show it running before you pay.'
  end
from (select level as n from dual connect by level <= 100)
order by n;

commit;

exit
