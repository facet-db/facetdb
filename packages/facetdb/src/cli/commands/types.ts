/**
 * `facetdb types`: a TypeScript declaration file with the answer column names and the union types
 * for choice and score values, plus Prisma and Drizzle snippets for the same columns. Answer column
 * names come from core's `answerColumns` and the status column names from core's constants, so this
 * command cannot disagree with the install SQL.
 *
 * Each source is written as its database keeps the answers: the scheme table's static `types`
 * (cli/engines.ts, no driver loaded) says what a raw read of a yes-or-no answer returns, the
 * Drizzle core and the Prisma provider the database has, and an engine with neither ORM gets one
 * comment line saying so instead of a wrong snippet. An API source keeps its answers in the FacetDB
 * store, and a source with no connection string (a config written in a test) reads as Postgres, so
 * a Postgres project's output is unchanged, byte for byte.
 */

const HEADER =
  "Generated by facetdb types. Do not edit by hand: run facetdb types again after the config changes.";

/**
 * The prefix of everything FacetDB adds to a database: its own columns, and the side table beside
 * a MySQL or SQL Server table. Inside MongoDB's `facetdb` subdocument the own fields drop it.
 */
const OWN_PREFIX = "facetdb_";

/** The subdocument each MongoDB document keeps its answers in. */
const SUBDOCUMENT = "facetdb";

/** FacetDB's own columns, which a subdocument names without the prefix (`facetdb.status`). */
const OWN_COLUMNS: ReadonlySet<string> = new Set([
  STATUS_COLUMN,
  UPDATED_AT_COLUMN,
  REVIEWED_COLUMN,
]);

/**
 * A column FacetDB stores on a record. `values` are the allowed values of a text column (option or
 * level names, or the record statuses) and the keys of a json column; a boolean or a real has none.
 */
type StoredColumn = {
  readonly name: string;
  readonly kind: AnswerColumnKind;
  readonly values: readonly string[];
  /** The status is always set once a record is queued, so its type has no null. */
  readonly required?: true;
};

/**
 * What the ORM snippets write: every stored column, plus the two bookkeeping columns an application
 * reads. The declaration file does not list the bookkeeping columns. The status is a text column
 * with its own, shorter type on the engines that size text.
 */
type OrmColumn = {
  readonly name: string;
  readonly kind: AnswerColumnKind | "status" | "timestamp";
  /** `facetdb_reviewed`, whose nullability and default are the engine's (`EngineTypes.reviewed`). */
  readonly reviewed?: true;
};

/** The database a source's answers are written to, by its name in words, and how it keeps them. */
type SourceEngine = {
  readonly database: string;
  readonly sql: boolean;
  readonly types: EngineTypes;
};

const POSTGRES: SourceEngine = { database: "Postgres", sql: true, types: POSTGRES_TYPES };

/**
 * The database a source's types follow: its connection string's, from the scheme table. An API
 * source's answers live in the FacetDB store, which is Postgres. A connection string read from a
 * variable that is not set here leaves the database unknown, and so does a scheme FacetDB does not
 * read: both are refused rather than guessed, since a wrong guess types a 1 as a boolean.
 * `connector: "polling"` is resolved as `engineFor` resolves it: refused for a database that is
 * not SQL, and otherwise the polling install's own columns (`POLLED_COLUMNS`) on that database.
 */
function engineOf(source: SourceConfig): SourceEngine {
  const found = schemeEngineOf(source);
  if (source.connector !== "polling" || source.table === undefined) {
    return found;
  }
  if (!found.sql) {
    throw new CliError(
      "connector-polling",
      `connector: "polling" scans the rows of a SQL table, and the source "${source.name}"'s connection string is ${found.database}'s, which FacetDB watches by its own change feed`,
      'remove connector: "polling" from the source in facetdb.config.ts',
    );
  }
  return {
    database: `${found.database}, watched by polling`,
    sql: true,
    types: { ...found.types, ...POLLED_COLUMNS },
  };
}

/** The database a source's connection string names, before any `connector:` override. */
function schemeEngineOf(source: SourceConfig): SourceEngine {
  if (source.table === undefined) {
    return POSTGRES;
  }
  if (source.database === undefined || source.database === "") {
    if (source.databaseEnv === undefined) {
      return POSTGRES;
    }
    throw new CliError(
      "database-url",
      `the source "${source.name}" has no connection string, so facetdb types cannot tell which database keeps its answers, and the types follow the database`,
      `set ${source.databaseEnv} to the source's connection string and run facetdb types again`,
    );
  }
  const found = typesOf(source.database);
  if (found === undefined) {
    throw new CliError(
      "unknown-scheme",
      `the connection string of the source "${source.name}" names no database FacetDB connects to, so facetdb types cannot tell which types its database keeps`,
      `use a connection string of one of the databases FacetDB connects to; they are listed, with the scheme each one's string starts with, at ${DATABASES_PAGE}`,
    );
  }
  return found;
}

function valuesOf(question: Question): readonly string[] {
  switch (question.type) {
    case "noul":
      return [];
    case "choice":
      return question.options.map((option) => option.name);
    case "score":
      return question.levels.map((level) => level.name);
  }
}

/**
 * The columns a source's questions add, in install order, then the status column. Answer columns
 * come from core's helper, so the suffixes are spelled only there. Two columns with one name (a
 * question whose answer column is named like another question) would be one declared member twice,
 * so the source is refused here, before any snippet is written.
 */
export function storedColumns(source: SourceConfig): readonly StoredColumn[] {
  const columns: StoredColumn[] = [
    ...source.questions.flatMap((question) =>
      answerColumns(question).map(
        (column): StoredColumn => ({
          name: column.name,
          kind: column.kind,
          values: valuesOf(question),
        }),
      ),
    ),
    { name: STATUS_COLUMN, kind: "text", values: RECORD_STATUSES, required: true },
  ];
  const seen = new Set<string>();
  for (const column of columns) {
    if (seen.has(column.name)) {
      throw new Error(
        `source "${source.name}" has two columns named "${column.name}": a question's answer column takes the name of another column; rename one question so that the names differ`,
      );
    }
    seen.add(column.name);
  }
  return columns;
}

function ormColumnsOf(source: SourceConfig): readonly OrmColumn[] {
  return [
    ...storedColumns(source).map(
      (column): OrmColumn =>
        column.required === true
          ? { name: column.name, kind: "status" }
          : { name: column.name, kind: column.kind },
    ),
    { name: UPDATED_AT_COLUMN, kind: "timestamp" },
    { name: REVIEWED_COLUMN, kind: "boolean", reviewed: true },
  ];
}

/** A column's name where the engine keeps it: a subdocument's own fields drop the `facetdb_` prefix. */
function storedName(name: string, types: EngineTypes): string {
  return types.answersIn === "subdocument" && OWN_COLUMNS.has(name)
    ? name.slice(OWN_PREFIX.length)
    : name;
}

/** Splits on anything that is not a letter or digit, and capitalises each part: `support_messages` becomes `SupportMessages`. */
function pascal(name: string): string {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter((part) => part !== "")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

/** The table's name, or the source's for an API source; the name every generated type is built from. */
function tableBase(source: SourceConfig): string {
  const base = pascal(source.table ?? source.name);
  if (!/^[A-Za-z]/.test(base)) {
    throw new Error(
      `"${source.table ?? source.name}" cannot become a type name; name the table with letters first`,
    );
  }
  return base;
}

/**
 * A column name as a camelCase field: `wants_refund` becomes `wantsRefund`. Where camelCase would
 * lose a separator, the underscore stays: an empty part (`a__b`, `a_`) and a part that starts with a
 * digit (`a_1`) keep it, so two different column names never map to one field (`a_1` and `a1` are
 * both valid question names; so are `a_b` and `a__b`).
 */
function camel(name: string): string {
  return name
    .split("_")
    .map((part, index) => {
      if (index === 0) {
        return part;
      }
      if (part === "") {
        return "_";
      }
      return /^[0-9]/.test(part) ? `_${part}` : part.charAt(0).toUpperCase() + part.slice(1);
    })
    .join("");
}

/** Plain identifiers stay bare, as a formatter would write them; anything else is quoted. */
function propertyKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

/** A column's TypeScript type as a raw read of the engine returns it. */
function tsType(column: StoredColumn, types: EngineTypes): string {
  const type = (() => {
    switch (column.kind) {
      case "boolean":
        return types.boolean.read;
      case "real":
        return "number";
      case "text":
        return column.values.map((value) => JSON.stringify(value)).join(" | ");
      case "json": {
        const shape = `{ ${column.values.map((value) => `${propertyKey(value)}: number`).join("; ")} }`;
        switch (types.json.read) {
          case "object":
            return shape;
          case "text":
          case "clob fetched as text":
            return "string";
          case "object or text":
            return `${shape} | string`;
        }
      }
    }
  })();
  const nullable = column.required !== true || types.statusNullUntil !== undefined;
  return nullable ? `${type} | null` : type;
}

/** How a raw read returns a choice's probabilities, in words. */
const JSON_READ: Readonly<Record<EngineTypes["json"]["read"], string>> = {
  object: "read as an object",
  text: "read as JSON text",
  "object or text": "read as an object, or as JSON text where json is a longtext (MariaDB)",
  "clob fetched as text":
    "read as JSON text once the application fetches clobs as strings (oracledb.fetchAsString = [oracledb.CLOB]), as a Lob to read otherwise",
};

/**
 * The comment lines above a source's type where its database keeps the answers otherwise than
 * Postgres: the types the install gives the source's columns and how a raw read returns them, a
 * nullable status, and MongoDB's subdocument. Postgres has none, so its declaration is unchanged.
 */
function declarationNotes(
  source: SourceConfig,
  engine: SourceEngine,
  columns: readonly StoredColumn[],
): readonly string[] {
  const { database, types } = engine;
  if (types === POSTGRES_TYPES) {
    return [];
  }
  const kinds = new Set(columns.map((column) => column.kind));
  const parts: string[] = [];
  if (kinds.has("boolean")) {
    const read = types.boolean.read === "boolean" ? "true or false" : "1 or 0";
    parts.push(`a yes-or-no answer is ${types.boolean.stored}, read as ${read}`);
  }
  if (kinds.has("real")) {
    parts.push(`a probability, confidence or expected value is ${types.real}`);
  }
  if (kinds.has("json")) {
    parts.push(`a choice's probabilities are ${types.json.stored}, ${JSON_READ[types.json.read]}`);
  }
  const notes = [`// The source "${source.name}" is on ${database}: ${parts.join("; ")}.`];
  if (types.statusNullUntil !== undefined) {
    notes.push(
      `// ${STATUS_COLUMN} is nullable on ${database}: ${types.statusNullUntil} reads null, which means pending.`,
    );
  }
  if (types.answersIn === "subdocument") {
    notes.push(
      `// ${tableBase(source)}Answers is each document's ${SUBDOCUMENT} subdocument (document.${SUBDOCUMENT}.<field>): ${database} keeps the answers as its fields, not as columns, and a field is absent until the worker first writes it.`,
    );
  }
  return notes;
}

/** The sources that write to a database table; an API source keeps its answers in the FacetDB store. */
function databaseSources(config: ProjectConfig): readonly SourceConfig[] {
  return config.sources.filter((source) => source.table !== undefined);
}

/**
 * A side-table source keeps its answers in a table of their own, keyed by the table's primary key:
 * `facetdb.<table>_answers` on Postgres, `facetdb_<table>_answers` beside the table where the
 * engine has no `facetdb` schema (MySQL, SQL Server). The config does not name that key, so the
 * snippets model the answer columns and leave the key field to the user.
 */
function answersTable(source: SourceConfig, types: EngineTypes): string {
  const table = `${source.table ?? source.name}_answers`;
  return types.sideTableIn === "facetdb schema" ? table : `${OWN_PREFIX}${table}`;
}

function lowerFirst(name: string): string {
  return `${name.charAt(0).toLowerCase()}${name.slice(1)}`;
}

/** Two sources whose table names give the same type name would overwrite each other. */
function assertUniqueTypeNames(config: ProjectConfig): void {
  const seen = new Map<string, string>();
  for (const source of config.sources) {
    const name = tableBase(source);
    const earlier = seen.get(name);
    if (earlier !== undefined) {
      throw new Error(
        `sources "${earlier}" and "${source.name}" both become the type ${name}Answers; rename one table or source so the names differ`,
      );
    }
    seen.set(name, source.name);
  }
}

/** The declaration file: one `<Table>Answers` type per source, with its answer columns and status. */
export function renderDeclaration(config: ProjectConfig): string {
  assertUniqueTypeNames(config);
  const types = config.sources.map((source) => {
    const engine = engineOf(source);
    const columns = storedColumns(source);
    const optional = engine.types.answersIn === "subdocument" ? "?" : "";
    const members = columns.map(
      (column) =>
        `  ${propertyKey(storedName(column.name, engine.types))}${optional}: ${tsType(column, engine.types)};`,
    );
    return [
      ...declarationNotes(source, engine, columns),
      `export type ${tableBase(source)}Answers = {\n${members.join("\n")}\n};\n`,
    ].join("\n");
  });
  return [`// ${HEADER}`, "", ...types].join("\n");
}

/** The one comment line that stands for a snippet an engine has no ORM for. */
function noSnippet(source: SourceConfig, engine: SourceEngine, why: string, what: string): string {
  const where = engine.types.answersIn === "subdocument" ? "fields" : "columns";
  return `// ${why} ${engine.database}, so the source "${source.name}" has no ${what}; its ${where} are typed in ${tableBase(source)}Answers in the declaration file.\n`;
}

type PrismaProvider = NonNullable<EngineTypes["prisma"]>;

/** A column's Prisma type, without its `?`, and the native type after `@map` where one is needed. */
type PrismaType = readonly [type: string, native?: string];

/**
 * Each provider's types for FacetDB's columns, as its install writes them: MySQL's float and
 * varchar(255), SQL Server's nvarchar and its JSON in text (Prisma has no Json there), SQLite's
 * JSON and time as text (FacetDB writes ISO text, not Prisma's own date storage).
 */
const PRISMA_TYPES: Readonly<
  Record<PrismaProvider, Readonly<Record<OrmColumn["kind"], PrismaType>>>
> = {
  postgresql: {
    boolean: ["Boolean"],
    real: ["Float", "@db.Real"],
    text: ["String"],
    status: ["String"],
    json: ["Json"],
    timestamp: ["DateTime", "@db.Timestamptz(6)"],
  },
  cockroachdb: {
    boolean: ["Boolean"],
    real: ["Float", "@db.Float4"],
    text: ["String"],
    status: ["String"],
    json: ["Json"],
    timestamp: ["DateTime", "@db.Timestamptz(6)"],
  },
  mysql: {
    boolean: ["Boolean"],
    real: ["Float", "@db.Float"],
    text: ["String", "@db.VarChar(255)"],
    status: ["String", "@db.VarChar(16)"],
    json: ["Json"],
    timestamp: ["DateTime", "@db.DateTime(3)"],
  },
  sqlserver: {
    boolean: ["Boolean"],
    real: ["Float", "@db.Real"],
    text: ["String", "@db.NVarChar(255)"],
    status: ["String", "@db.VarChar(16)"],
    json: ["String", "@db.NVarChar(Max)"],
    timestamp: ["DateTime", "@db.DateTime2"],
  },
  sqlite: {
    boolean: ["Boolean"],
    real: ["Float"],
    text: ["String"],
    status: ["String"],
    json: ["String"],
    timestamp: ["String"],
  },
  mongodb: {
    boolean: ["Boolean"],
    real: ["Float"],
    text: ["String"],
    status: ["String"],
    json: ["Json"],
    timestamp: ["DateTime"],
  },
};

/** One Prisma field line: `wantsRefund Boolean? @map("wants_refund")`. */
function prismaField(provider: PrismaProvider, types: EngineTypes, column: OrmColumn): string {
  const name = storedName(column.name, types);
  const [type, native] = PRISMA_TYPES[provider][column.kind];
  const quoted = JSON.stringify(name);
  // Every column is optional but reviewed, which follows its install: not null with a false default
  // on the trigger installs, nullable with one on the polling installs, nullable with none on SQL
  // Server, absent until set on MongoDB.
  const typed =
    column.reviewed === true
      ? `${type}${types.reviewed.nullable ? "?" : ""}${types.reviewed.defaultFalse ? " @default(false)" : ""}`
      : `${type}?`;
  return `  ${camel(name)} ${typed} @map(${quoted})${native === undefined ? "" : ` ${native}`}`;
}

/** A source's Prisma block: fields for your model, a side-table model, or MongoDB's composite type. */
function prismaBlock(source: SourceConfig, engine: SourceEngine, provider: PrismaProvider): string {
  const { types } = engine;
  const fields = ormColumnsOf(source).map((column) => prismaField(provider, types, column));
  const base = tableBase(source);
  if (types.answersIn === "subdocument") {
    return [
      `// The ${SUBDOCUMENT} subdocument of each document: add ${SUBDOCUMENT} ${base}Facetdb? to your model for the collection ${JSON.stringify(source.table ?? source.name)}.`,
      `type ${base}Facetdb {`,
      ...fields,
      "}\n",
    ].join("\n");
  }
  if (source.storage !== "side-table") {
    return `model ${base} {\n${fields.join("\n")}\n}\n`;
  }
  const table = answersTable(source, types);
  if (types.sideTableIn === "facetdb schema") {
    return [
      `// Side table facetdb.${table}: the answers, keyed by your primary key. Add the key field yourself; the config does not name it.`,
      `model ${base}Answers {`,
      ...fields,
      '  @@schema("facetdb")',
      `  @@map(${JSON.stringify(table)})`,
      "}\n",
    ].join("\n");
  }
  return [
    `// Side table ${table}, beside your table: the answers, keyed by your primary key. Add the key field yourself; the config does not name it.`,
    `model ${base}Answers {`,
    ...fields,
    `  @@map(${JSON.stringify(table)})`,
    "}\n",
  ].join("\n");
}

/** Blocks gathered under one key (a Prisma provider, a Drizzle core), with the databases they are on. */
type Group = { readonly databases: Set<string>; readonly blocks: string[] };

/**
 * The Prisma snippet: the fields of each database table, mapped to their column names. An inline
 * table's fields go into your own model for it; a side-table source gets a new model for its
 * answers; a MongoDB source a composite type for its subdocument. A Prisma schema has one
 * datasource, so the models are grouped by provider, each group under a line naming it; a project
 * whose every source is on Postgres keeps its output, with no such line.
 */
export function renderPrisma(config: ProjectConfig): string {
  assertUniqueTypeNames(config);
  const groups = new Map<PrismaProvider, Group>();
  const missing: string[] = [];
  for (const source of databaseSources(config)) {
    const engine = engineOf(source);
    const provider = engine.types.prisma;
    if (provider === undefined) {
      missing.push(noSnippet(source, engine, "Prisma has no provider for", "Prisma model"));
      continue;
    }
    const group = groups.get(provider) ?? { databases: new Set(), blocks: [] };
    groups.set(provider, group);
    group.databases.add(engine.database);
    group.blocks.push(prismaBlock(source, engine, provider));
  }
  const named = [...groups.keys()].some((provider) => provider !== "postgresql");
  const models = [...groups].flatMap(([provider, group]) => [
    ...(named
      ? [
          `// For a Prisma schema whose datasource has provider = ${JSON.stringify(provider)} (${[...group.databases].join(", ")}):`,
        ]
      : []),
    ...group.blocks,
  ]);
  return [
    `// ${HEADER}`,
    "// Paste each model's fields into your own model for that table; it keeps its own id and columns.",
    "",
    ...models,
    ...missing,
  ].join("\n");
}

type DrizzleCore = NonNullable<EngineTypes["drizzle"]>;

/** One column as Drizzle writes it: the builder it imports and the column expression. */
type DrizzleColumn = { readonly builder: string; readonly expression: string };

function pgColumn(column: OrmColumn, quoted: string): DrizzleColumn {
  switch (column.kind) {
    case "boolean":
      return { builder: "boolean", expression: `boolean(${quoted})` };
    case "real":
      return { builder: "real", expression: `real(${quoted})` };
    case "text":
    case "status":
      return { builder: "text", expression: `text(${quoted})` };
    case "json":
      return { builder: "jsonb", expression: `jsonb(${quoted})` };
    case "timestamp":
      return { builder: "timestamp", expression: `timestamp(${quoted}, { withTimezone: true })` };
  }
}

/** MySQL's and MariaDB's: `boolean` is tinyint(1), a real is `float`, text is sized as the install sizes it. */
function mysqlColumn(column: OrmColumn, quoted: string): DrizzleColumn {
  switch (column.kind) {
    case "boolean":
      return { builder: "boolean", expression: `boolean(${quoted})` };
    case "real":
      return { builder: "float", expression: `float(${quoted})` };
    case "text":
      return { builder: "varchar", expression: `varchar(${quoted}, { length: 255 })` };
    case "status":
      return { builder: "varchar", expression: `varchar(${quoted}, { length: 16 })` };
    case "json":
      return { builder: "json", expression: `json(${quoted})` };
    case "timestamp":
      return { builder: "datetime", expression: `datetime(${quoted}, { fsp: 3 })` };
  }
}

/** SQLite's and libSQL's: a boolean is an integer 0 or 1, JSON and the time are text. */
function sqliteColumn(column: OrmColumn, quoted: string): DrizzleColumn {
  switch (column.kind) {
    case "boolean":
      return { builder: "integer", expression: `integer(${quoted}, { mode: "boolean" })` };
    case "real":
      return { builder: "real", expression: `real(${quoted})` };
    case "text":
    case "status":
      return { builder: "text", expression: `text(${quoted})` };
    case "json":
      return { builder: "text", expression: `text(${quoted}, { mode: "json" })` };
    case "timestamp":
      return { builder: "text", expression: `text(${quoted})` };
  }
}

/** Each Drizzle core: its column builders and the function that defines a table with them. */
const DRIZZLE: Readonly<
  Record<
    DrizzleCore,
    {
      readonly column: (column: OrmColumn, quoted: string) => DrizzleColumn;
      readonly table: string;
    }
  >
> = {
  "pg-core": { column: pgColumn, table: "pgTable" },
  "mysql-core": { column: mysqlColumn, table: "mysqlTable" },
  "sqlite-core": { column: sqliteColumn, table: "sqliteTable" },
};

function drizzleColumn(core: DrizzleCore, types: EngineTypes, column: OrmColumn): DrizzleColumn {
  const built = DRIZZLE[core].column(column, JSON.stringify(column.name));
  return column.reviewed === true && types.reviewed.defaultFalse
    ? { ...built, expression: `${built.expression}.default(false)` }
    : built;
}

/** A source's Drizzle block: the columns to spread into your own table, or into its side table. */
function drizzleBlock(
  source: SourceConfig,
  types: EngineTypes,
  core: DrizzleCore,
  builders: Set<string>,
): string {
  const fields = ormColumnsOf(source).map((column) => {
    const built = drizzleColumn(core, types, column);
    builders.add(built.builder);
    return `  ${camel(column.name)}: ${built.expression},`;
  });
  const base = tableBase(source);
  if (source.storage !== "side-table") {
    const variable = `${lowerFirst(base)}Facetdb`;
    const table = JSON.stringify(source.table ?? source.name);
    return [
      `// Spread into your own ${DRIZZLE[core].table}(${table}, { ... }) definition.`,
      `export const ${variable} = {\n${fields.join("\n")}\n};\n`,
    ].join("\n");
  }
  const table = JSON.stringify(answersTable(source, types));
  const where =
    types.sideTableIn === "facetdb schema"
      ? `Side table in the facetdb schema: facetdbSchema.table(${table}, { ... })`
      : `Side table beside your table: ${DRIZZLE[core].table}(${table}, { ... })`;
  return [
    `// ${where}, keyed by your primary key. Add that key column yourself; the config does not name it.`,
    `export const ${lowerFirst(base)}AnswersFacetdb = {\n${fields.join("\n")}\n};\n`,
  ].join("\n");
}

/**
 * The Drizzle snippet: the columns of each database table, to spread into your own table
 * definition. A side-table source gets its answers' columns, to spread into its side table. Each
 * Drizzle core has builders of its own (two `boolean`s cannot share a file), so the columns are
 * grouped by core, each group with its import line, under a line naming its databases when the
 * project spans more than one core.
 */
export function renderDrizzle(config: ProjectConfig): string {
  assertUniqueTypeNames(config);
  const groups = new Map<DrizzleCore, Group & { readonly builders: Set<string> }>();
  const missing: string[] = [];
  for (const source of databaseSources(config)) {
    const engine = engineOf(source);
    const core = engine.types.drizzle;
    if (core === undefined) {
      missing.push(noSnippet(source, engine, "Drizzle has no driver for", "Drizzle snippet"));
      continue;
    }
    const group = groups.get(core) ?? { databases: new Set(), blocks: [], builders: new Set() };
    groups.set(core, group);
    group.databases.add(engine.database);
    group.blocks.push(drizzleBlock(source, engine.types, core, group.builders));
  }
  if (groups.size === 0) {
    return [`// ${HEADER}`, "", ...(missing.length === 0 ? [""] : missing)].join("\n");
  }
  const parts = [...groups].flatMap(([core, group]) => [
    ...(groups.size > 1
      ? [
          `// The sources on ${[...group.databases].join(", ")}, for a schema file of their own: each Drizzle core has builders of its own.`,
        ]
      : []),
    `import { ${[...group.builders].sort().join(", ")} } from "drizzle-orm/${core}";`,
    "",
    ...group.blocks,
  ]);
  return [`// ${HEADER}`, ...parts, ...missing].join("\n");
}

/** What `facetdb types` writes and prints. */
export type TypesOptions = {
  /** Where the declaration file goes; the caller resolves it against the project directory. */
  readonly out: string;
  /** Print the Prisma snippet too. */
  readonly prisma: boolean;
  /** Print the Drizzle snippet too. */
  readonly drizzle: boolean;
  /** Print everything and write nothing. */
  readonly dryRun: boolean;
};

/** The side effects `runTypes` needs, passed in so a test can fake them (no module is patched). */
export type TypesDeps = {
  readonly writeFile: (path: string, text: string) => Promise<void>;
  readonly print: (text: string) => void;
};

/**
 * Writes the declaration file and prints the snippets asked for. The snippets are for pasting into
 * the user's own schema, so they are printed, not written. With `--dry-run` the declaration is
 * printed as well and nothing is written.
 */
export async function runTypes(
  config: ProjectConfig,
  options: TypesOptions,
  deps: TypesDeps,
): Promise<void> {
  const declaration = renderDeclaration(config);
  if (options.dryRun) {
    deps.print(declaration);
  } else {
    await deps.writeFile(options.out, declaration);
    deps.print(`wrote ${options.out}`);
  }
  if (options.prisma) {
    deps.print(renderPrisma(config));
  }
  if (options.drizzle) {
    deps.print(renderDrizzle(config));
  }
}

/** The declaration file's default name, beside the config in the project directory. */
export const TYPES_FILE = "facetdb.types.d.ts";

type TypesCommandOptions = {
  readonly config: string;
  readonly out: string;
  readonly prisma?: boolean;
  readonly drizzle?: boolean;
};

/** The words for an `--out` that names something facetdb types did not write, which it never replaces. */
function notGenerated(out: string, what: string): CliError {
  return new CliError(
    "types-out-exists",
    `${out} ${what}, and facetdb types replaces only a declaration file it wrote itself (one whose first line is "// ${HEADER}"); nothing was written`,
    `pass --out with another file name, or move ${out} away and run facetdb types again`,
  );
}

/** One text as the parts `Workspace.writeParts` takes. */
async function* single(text: string): AsyncGenerator<string> {
  yield text;
}

/**
 * `facetdb types` as the program registers it: it reads the config and nothing else (no engine is
 * loaded, no database is reached; the scheme table says how each source's database keeps its
 * answers). The declaration file is generated and says so in its first line, so a run replaces the
 * file the last run wrote, and nothing else: a file whose first line is not the generated header
 * (a hand-written `global.d.ts`), a symbolic link or a directory at `--out` is refused, also by a
 * dry run, since the real run would stop there. The file is written beside and renamed into place,
 * so a link put there meanwhile is replaced, never written through. `--out` must name a `.d.ts`
 * file, so a mistyped path never reaches a source file of the application.
 */
export const typesCommand = defineCommand<TypesCommandOptions>("types", {
  description:
    "Writes a TypeScript declaration file with the answer column names and union types for choice and score values, typed as each source's database returns them, plus Prisma and Drizzle snippets for that database",
  options: [
    {
      flags: "--config <path>",
      description: "the config file",
      defaultValue: "facetdb.config.ts",
    },
    {
      flags: "--out <file>",
      description:
        "the declaration file to write (a later run replaces the one it wrote, nothing else)",
      defaultValue: TYPES_FILE,
    },
    { flags: "--prisma", description: "also print the Prisma snippet for each source's database" },
    {
      flags: "--drizzle",
      description: "also print the Drizzle snippet for each source's database",
    },
  ],
  run: async ({ options, deps, print }) => {
    if (!options.out.endsWith(".d.ts")) {
      throw new CliError(
        "usage",
        `--out names "${options.out}", and facetdb types writes a declaration file, whose name ends in .d.ts, so it never writes over another kind of file`,
        `pass --out <name>.d.ts, or leave --out out to write ${TYPES_FILE}`,
        EXIT_USAGE,
      );
    }
    const config = await loadProjectConfig(deps, options.config);
    const found = await deps.workspace.peek(options.out);
    if (found.kind === "other") {
      throw notGenerated(options.out, "is a symbolic link or a directory, not a file");
    }
    if (found.kind === "file" && found.firstLine !== `// ${HEADER}`) {
      throw notGenerated(options.out, "exists and was not written by facetdb types");
    }
    const prisma = options.prisma === true;
    const drizzle = options.drizzle === true;
    await runTypes(
      config,
      { out: options.out, prisma, drizzle, dryRun: options.dryRun },
      {
        writeFile: async (path, text) => {
          // Replaces only the generated file seen above; a file that appeared since is kept.
          const written = await deps.workspace.writeParts(path, single(text), {
            overwrite: found.kind === "file",
          });
          if (written === "exists") {
            throw notGenerated(path, "appeared while facetdb types ran");
          }
        },
        print,
      },
    );
    return { out: options.out, written: !options.dryRun, prisma, drizzle };
  },
});
