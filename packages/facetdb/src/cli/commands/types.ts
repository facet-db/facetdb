import {
  type AnswerColumnKind,
  answerColumns,
  type Question,
  RECORD_STATUSES,
  REVIEWED_COLUMN,
  STATUS_COLUMN,
  UPDATED_AT_COLUMN,
} from "@facetdb/core";
import type { ProjectConfig, SourceConfig } from "../../config/index.ts";

/**
 * `facetdb types`: a TypeScript declaration file with the answer column names and the union types
 * for choice and score values, plus Prisma and Drizzle snippets for the same columns. Answer column
 * names come from core's `answerColumns` and the status column names from core's constants, so
 * this command cannot disagree with the install SQL.
 */

const HEADER =
  "Generated by facetdb types. Do not edit by hand: run facetdb types again after the config changes.";

/**
 * A column FacetDB stores on a record. `values` are the allowed values of a text column (option or
 * level names, or the record statuses) and the keys of a json column; a boolean or a real has none.
 */
type StoredColumn = {
  readonly name: string;
  readonly kind: AnswerColumnKind;
  readonly values: readonly string[];
  /** The status is always set once a record is queued, so its type has no null. */
  readonly required?: true;
};

/**
 * What the ORM snippets write: every stored column, plus the two bookkeeping columns an application
 * reads. The declaration file does not list the bookkeeping columns.
 */
type OrmColumn = {
  readonly name: string;
  readonly kind: AnswerColumnKind | "timestamp";
  /** A boolean that starts false (`facetdb_reviewed`). */
  readonly defaultFalse?: true;
};

/** One column as Prisma and Drizzle write it: the field line and the Drizzle column expression. */
type OrmField = {
  readonly name: string;
  readonly prisma: string;
  readonly drizzleBuilder: string;
  readonly drizzle: string;
};

function valuesOf(question: Question): readonly string[] {
  switch (question.type) {
    case "noul":
      return [];
    case "choice":
      return question.options.map((option) => option.name);
    case "score":
      return question.levels.map((level) => level.name);
  }
}

/**
 * The columns a source's questions add, in install order, then the status column. Answer columns
 * come from core's helper, so the suffixes are spelled only there. Two columns with one name (a
 * question whose answer column is named like another question) would be one declared member twice,
 * so the source is refused here, before any snippet is written.
 */
export function storedColumns(source: SourceConfig): readonly StoredColumn[] {
  const columns: StoredColumn[] = [
    ...source.questions.flatMap((question) =>
      answerColumns(question).map(
        (column): StoredColumn => ({
          name: column.name,
          kind: column.kind,
          values: valuesOf(question),
        }),
      ),
    ),
    { name: STATUS_COLUMN, kind: "text", values: RECORD_STATUSES, required: true },
  ];
  const seen = new Set<string>();
  for (const column of columns) {
    if (seen.has(column.name)) {
      throw new Error(
        `source "${source.name}" has two columns named "${column.name}": a question's answer column takes the name of another column; rename one question so that the names differ`,
      );
    }
    seen.add(column.name);
  }
  return columns;
}

function ormColumnsOf(source: SourceConfig): readonly OrmColumn[] {
  return [
    ...storedColumns(source),
    { name: UPDATED_AT_COLUMN, kind: "timestamp" },
    { name: REVIEWED_COLUMN, kind: "boolean", defaultFalse: true },
  ];
}

/** Splits on anything that is not a letter or digit, and capitalises each part: `support_messages` becomes `SupportMessages`. */
function pascal(name: string): string {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter((part) => part !== "")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

/** The table's name, or the source's for an API source; the name every generated type is built from. */
function tableBase(source: SourceConfig): string {
  const base = pascal(source.table ?? source.name);
  if (!/^[A-Za-z]/.test(base)) {
    throw new Error(
      `"${source.table ?? source.name}" cannot become a type name; name the table with letters first`,
    );
  }
  return base;
}

/**
 * A column name as a camelCase field: `wants_refund` becomes `wantsRefund`. Where camelCase would
 * lose a separator, the underscore stays: an empty part (`a__b`, `a_`) and a part that starts with a
 * digit (`a_1`) keep it, so two different column names never map to one field (`a_1` and `a1` are
 * both valid question names; so are `a_b` and `a__b`).
 */
function camel(name: string): string {
  return name
    .split("_")
    .map((part, index) => {
      if (index === 0) {
        return part;
      }
      if (part === "") {
        return "_";
      }
      return /^[0-9]/.test(part) ? `_${part}` : part.charAt(0).toUpperCase() + part.slice(1);
    })
    .join("");
}

/** Plain identifiers stay bare, as a formatter would write them; anything else is quoted. */
function propertyKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function tsType(column: StoredColumn): string {
  const type = (() => {
    switch (column.kind) {
      case "boolean":
        return "boolean";
      case "real":
        return "number";
      case "text":
        return column.values.map((value) => JSON.stringify(value)).join(" | ");
      case "json":
        return `{ ${column.values.map((value) => `${propertyKey(value)}: number`).join("; ")} }`;
    }
  })();
  return column.required === true ? type : `${type} | null`;
}

/** The sources that write to a database table; an API source keeps its answers in the FacetDB store. */
function databaseSources(config: ProjectConfig): readonly SourceConfig[] {
  return config.sources.filter((source) => source.table !== undefined);
}

/**
 * A side-table source keeps its answers in `facetdb.<table>_answers`, keyed by the table's primary
 * key. The config does not name that key, so the snippets model the answer columns and leave the
 * key field to the user.
 */
function answersTable(source: SourceConfig): string {
  return `${source.table ?? source.name}_answers`;
}

function lowerFirst(name: string): string {
  return `${name.charAt(0).toLowerCase()}${name.slice(1)}`;
}

/** Two sources whose table names give the same type name would overwrite each other. */
function assertUniqueTypeNames(config: ProjectConfig): void {
  const seen = new Map<string, string>();
  for (const source of config.sources) {
    const name = tableBase(source);
    const earlier = seen.get(name);
    if (earlier !== undefined) {
      throw new Error(
        `sources "${earlier}" and "${source.name}" both become the type ${name}Answers; rename one table or source so the names differ`,
      );
    }
    seen.set(name, source.name);
  }
}

/** The declaration file: one `<Table>Answers` type per source, with its answer columns and status. */
export function renderDeclaration(config: ProjectConfig): string {
  assertUniqueTypeNames(config);
  const types = config.sources.map((source) => {
    const members = storedColumns(source).map(
      (column) => `  ${propertyKey(column.name)}: ${tsType(column)};`,
    );
    return `export type ${tableBase(source)}Answers = {\n${members.join("\n")}\n};\n`;
  });
  return [`// ${HEADER}`, "", ...types].join("\n");
}

function ormField(column: OrmColumn): OrmField {
  const quoted = JSON.stringify(column.name);
  switch (column.kind) {
    case "boolean":
      return column.defaultFalse === true
        ? {
            name: column.name,
            prisma: `Boolean @default(false) @map(${quoted})`,
            drizzleBuilder: "boolean",
            drizzle: `boolean(${quoted}).default(false)`,
          }
        : {
            name: column.name,
            prisma: `Boolean? @map(${quoted})`,
            drizzleBuilder: "boolean",
            drizzle: `boolean(${quoted})`,
          };
    case "real":
      return {
        name: column.name,
        prisma: `Float? @map(${quoted}) @db.Real`,
        drizzleBuilder: "real",
        drizzle: `real(${quoted})`,
      };
    case "text":
      return {
        name: column.name,
        prisma: `String? @map(${quoted})`,
        drizzleBuilder: "text",
        drizzle: `text(${quoted})`,
      };
    case "json":
      return {
        name: column.name,
        prisma: `Json? @map(${quoted})`,
        drizzleBuilder: "jsonb",
        drizzle: `jsonb(${quoted})`,
      };
    case "timestamp":
      return {
        name: column.name,
        prisma: `DateTime? @map(${quoted}) @db.Timestamptz(6)`,
        drizzleBuilder: "timestamp",
        drizzle: `timestamp(${quoted}, { withTimezone: true })`,
      };
  }
}

/**
 * The Prisma snippet: the fields of each database table, mapped to their column names. An inline
 * table's fields go into your own model for it; a side-table source gets a new model for its answers.
 */
export function renderPrisma(config: ProjectConfig): string {
  assertUniqueTypeNames(config);
  const models = databaseSources(config).map((source) => {
    const fields = ormColumnsOf(source).map((column) => {
      const field = ormField(column);
      return `  ${camel(field.name)} ${field.prisma}`;
    });
    if (source.storage !== "side-table") {
      return `model ${tableBase(source)} {\n${fields.join("\n")}\n}\n`;
    }
    const table = answersTable(source);
    return [
      `// Side table facetdb.${table}: the answers, keyed by your primary key. Add the key field yourself; the config does not name it.`,
      `model ${tableBase(source)}Answers {`,
      ...fields,
      '  @@schema("facetdb")',
      `  @@map(${JSON.stringify(table)})`,
      "}\n",
    ].join("\n");
  });
  return [
    `// ${HEADER}`,
    "// Paste each model's fields into your own model for that table; it keeps its own id and columns.",
    "",
    ...models,
  ].join("\n");
}

/**
 * The Drizzle snippet: the columns of each database table, to spread into your own pgTable. A
 * side-table source gets its answers' columns, to spread into a table in the facetdb schema.
 */
export function renderDrizzle(config: ProjectConfig): string {
  assertUniqueTypeNames(config);
  const builders = new Set<string>();
  const blocks = databaseSources(config).map((source) => {
    const fields = ormColumnsOf(source).map((column) => {
      const field = ormField(column);
      builders.add(field.drizzleBuilder);
      return `  ${camel(field.name)}: ${field.drizzle},`;
    });
    const base = tableBase(source);
    if (source.storage !== "side-table") {
      const variable = `${lowerFirst(base)}Facetdb`;
      const table = JSON.stringify(source.table ?? source.name);
      return [
        `// Spread into your own pgTable(${table}, { ... }) definition.`,
        `export const ${variable} = {\n${fields.join("\n")}\n};\n`,
      ].join("\n");
    }
    const table = JSON.stringify(answersTable(source));
    return [
      `// Side table in the facetdb schema: facetdbSchema.table(${table}, { ... }), keyed by your primary key. Add that key column yourself; the config does not name it.`,
      `export const ${lowerFirst(base)}AnswersFacetdb = {\n${fields.join("\n")}\n};\n`,
    ].join("\n");
  });
  const imports = [...builders].sort();
  return [
    `// ${HEADER}`,
    imports.length === 0 ? "" : `import { ${imports.join(", ")} } from "drizzle-orm/pg-core";`,
    "",
    ...blocks,
  ].join("\n");
}

/** What `facetdb types` writes and prints. */
export type TypesOptions = {
  /** Where the declaration file goes; the caller resolves it against the project directory. */
  readonly out: string;
  /** Print the Prisma snippet too. */
  readonly prisma: boolean;
  /** Print the Drizzle snippet too. */
  readonly drizzle: boolean;
  /** Print everything and write nothing. */
  readonly dryRun: boolean;
};

/** The side effects `runTypes` needs, passed in so a test can fake them (no module is patched). */
export type TypesDeps = {
  readonly writeFile: (path: string, text: string) => Promise<void>;
  readonly print: (text: string) => void;
};

/**
 * Writes the declaration file and prints the snippets asked for. The snippets are for pasting into
 * the user's own schema, so they are printed, not written. With `--dry-run` the declaration is
 * printed as well and nothing is written.
 */
export async function runTypes(
  config: ProjectConfig,
  options: TypesOptions,
  deps: TypesDeps,
): Promise<void> {
  const declaration = renderDeclaration(config);
  if (options.dryRun) {
    deps.print(declaration);
  } else {
    await deps.writeFile(options.out, declaration);
    deps.print(`wrote ${options.out}`);
  }
  if (options.prisma) {
    deps.print(renderPrisma(config));
  }
  if (options.drizzle) {
    deps.print(renderDrizzle(config));
  }
}
